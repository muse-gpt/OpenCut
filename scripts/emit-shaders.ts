#!/usr/bin/env node
/**
 * Emit the GPU compositor shader bundles from the native module into the
 * TypeScript package.
 *
 * The bundles come from the same UCF kernels the D3D12 compositor dispatches,
 * so the Web/WASM path imports generated WGSL that already agrees with the
 * native renderer. Runs right after `build:napi`.
 */
import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { nodeFileName, packageDir, resolveTarget } from './platform.ts';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = resolveTarget();
const header = '// generated by scripts/emit-shaders.ts — do not edit';

interface ShaderBinding {
    resource: number;
    class: string;
    index: number;
}

interface ShaderMinSize {
    resource: number;
    element_bytes: number;
    min_elements_static: number;
    count_dependent: boolean;
}

interface ShaderFieldOffset {
    name: string;
    byte_offset: number;
}

interface ShaderManifest {
    abi_version: number;
    workgroup: [number, number, number];
    bindings: ShaderBinding[];
    min_binding_sizes: ShaderMinSize[];
    field_offsets: ShaderFieldOffset[];
    param_bytes: number;
    program_hash: number;
}

interface ShaderBundle {
    name: string;
    wgsl: string;
    manifest: ShaderManifest;
}

interface NativeBinding {
    gpuShaderBundles(): string;
}

const require = createRequire(import.meta.url);

function loadNative(): NativeBinding {
    const artifact = path.join(packageDir(root, target), nodeFileName(target));
    if (!fs.existsSync(artifact)) {
        throw new Error(`native artifact not found: ${artifact}\nRun \`pnpm run build:napi\` first.`);
    }
    return require(artifact) as NativeBinding;
}

function emit(): void {
    const bundles = JSON.parse(loadNative().gpuShaderBundles()) as ShaderBundle[];
    const outDir = path.join(root, 'projects', 'packages', 'open-cut', 'src', 'generated');
    const wgslDir = path.join(outDir, 'gpu');
    fs.rmSync(wgslDir, { recursive: true, force: true });
    fs.mkdirSync(wgslDir, { recursive: true });
    const shaders = bundles.map((bundle) => {
        const file = `gpu/${bundle.name}.wgsl`;
        fs.writeFileSync(path.join(outDir, file), `${header}\n${bundle.wgsl}`, 'utf8');
        return { name: bundle.name, file, manifest: bundle.manifest };
    });
    const document = { comment: header, shaders };
    fs.writeFileSync(path.join(outDir, 'gpu-shaders.json'), `${JSON.stringify(document, null, 4)}\n`, 'utf8');
    console.log(`emitted ${shaders.length} shader bundles -> ${path.relative(root, outDir)}`);
}

emit();
